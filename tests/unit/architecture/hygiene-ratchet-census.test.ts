import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import ts from 'typescript';
import { describe, expect, it } from 'vitest';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(HERE, '..', '..', '..');
const BASELINE_PATH = path.join(REPO_ROOT, 'tests', 'fixtures', 'architecture', 'hygiene-ratchet-census.baseline.json');

/** The repo-relative root the census scans. `<repo>/src/` is the only source tree. */
const SCAN_ROOT = 'src';
const PRUNED_DIRS = new Set(['node_modules', 'dist', 'tests', 'coverage']);
const OVERSIZE_LIMIT = 800;
/** A helper name must be declared at least this many times before it is a "copy". */
const HELPER_COPY_MIN = 2;

const BASELINE_NOTE =
  'RATCHET: 本文件的每一项读数只许下调，上调需 RECORDED CHANGE —— 仅当重构确实让读数变大（例如把两份副本合并成一份公共实现之外的诚实形状）时，' +
  '才在同一提交里写一段带日期的 RECORDED CHANGE，点名文件、旧→新读数与理由。下调基线是被鼓励的但非必需：' +
  '并行的重构任务让读数下降时本判据只打印 `可下调基线`，绝不因此判红。';

// ---------------------------------------------------------------------------
// Types
