/** `wc -l` semantics: a trailing newline terminates the last line, it does not add one. */
function lineCount(text: string): number {
  return text.split('\n').length - (text.endsWith('\n') ? 1 : 0);
}

const MODULE_LET = /^(?:export\s+)?let\s/;
const MODULE_NEW_CONTAINER = /^(?:export\s+)?const\s+[A-Za-z_$][\w$]*.*=\s*new\s+(?:Map|Set|WeakMap)\b/;

/**
 * Module-level mutable state by the proposal's line-wise shape: a column-0 line starting with
 * `let `/`export let `, or a module-level `const <id> … = new Map|Set|WeakMap`. Indented `let`
 * (function locals) never matches.
 */
export function countModuleMutableState(text: string): number {
  let count = 0;
  for (const line of text.split('\n')) {
    if (MODULE_LET.test(line) || MODULE_NEW_CONTAINER.test(line)) count += 1;
  }
  return count;
}

/**
 * Names of the single-statement `function` declarations in one file. Syntax tree, not text: a
 * `function` keyword inside a string/comment is not a declaration, and `async function` or a
 * generic `function f<T>(…)` is still one. A declaration with an empty or multi-statement body is
 * NOT counted — this dimension is about the copy-paste one-liner helper shape.
 */
export function singleStatementHelperNames(file: SourceFile): string[] {
  const sourceFile = ts.createSourceFile(file.path, file.text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  const names: string[] = [];
  const visit = (node: ts.Node): void => {
    if (ts.isFunctionDeclaration(node) && node.name && node.body && ts.isBlock(node.body) && node.body.statements.length === 1) {
      names.push(node.name.text);
    }
    ts.forEachChild(node, visit);
  };
  visit(sourceFile);
  return names;
}

/** The three dimensions over one source set. Deterministic: keys are inserted in sorted order. */
export function measure(sources: readonly SourceFile[]): Readings {
  const oversizeFiles: Record<string, number> = {};
  const moduleMutableState: Record<string, number> = {};
  const helperDeclarationsByName = new Map<string, string[]>();

  for (const file of [...sources].sort((a, b) => a.path.localeCompare(b.path))) {
    const lines = lineCount(file.text);
    if (lines > OVERSIZE_LIMIT) oversizeFiles[file.path] = lines;

    const mutable = countModuleMutableState(file.text);
    if (mutable > 0) moduleMutableState[file.path] = mutable;

    for (const name of singleStatementHelperNames(file)) {
      const declaringFiles = helperDeclarationsByName.get(name) ?? [];
      declaringFiles.push(file.path);
      helperDeclarationsByName.set(name, declaringFiles);
    }
  }

  const smallHelperCopies: Record<string, number> = {};
  const smallHelperFiles: Record<string, string[]> = {};
  for (const name of [...helperDeclarationsByName.keys()].sort()) {
    const declaringFiles = helperDeclarationsByName.get(name) ?? [];
    if (declaringFiles.length < HELPER_COPY_MIN) continue;
    smallHelperCopies[name] = declaringFiles.length;
    smallHelperFiles[name] = declaringFiles;
  }

  return { oversizeFiles, moduleMutableState, smallHelperCopies, smallHelperFiles };
}

/** The single integer the AC prints for dimension three. */
export function totalHelperCopies(readings: Readings): number {
  return Object.values(readings.smallHelperCopies).reduce((total, count) => total + count, 0);
}

