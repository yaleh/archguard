/** A baseline document derived from a reading — what the write-baseline seam commits. */
export function baselineFrom(readings: Readings, measuredAt: string): Baseline {
  return {
    measuredAt,
    note: BASELINE_NOTE,
    oversizeFiles: { ...readings.oversizeFiles },
    moduleMutableState: { ...readings.moduleMutableState },
    smallHelperCopies: { ...readings.smallHelperCopies },
    smallHelperCopiesTotal: totalHelperCopies(readings),
  };
}

function readNumberMap(record: Record<string, unknown>, key: string): Record<string, number> {
  const value = record[key];
  expect(typeof value === 'object' && value !== null && !Array.isArray(value), `baseline.${key} must be an object`).toBe(true);
  const out: Record<string, number> = {};
  for (const [name, count] of Object.entries(value as Record<string, unknown>)) {
    expect(
      typeof count === 'number' && Number.isInteger(count) && count >= 0,
      `baseline.${key}.${name} must be a non-negative integer`,
    ).toBe(true);
    out[name] = count as number;
  }
  return out;
}

export function readBaseline(): Baseline {
  const raw: unknown = JSON.parse(fs.readFileSync(BASELINE_PATH, 'utf8'));
  expect(typeof raw === 'object' && raw !== null, 'the baseline must be a JSON object').toBe(true);
  const record = raw as Record<string, unknown>;
  expect(typeof record.measuredAt === 'string' && /^\d{4}-\d{2}-\d{2}/.test(record.measuredAt as string), 'baseline.measuredAt must carry a date').toBe(true);
  expect(typeof record.note === 'string' && (record.note as string).length > 0, 'baseline.note must be a non-empty string').toBe(true);
  const total = record.smallHelperCopiesTotal;
  expect(typeof total === 'number' && Number.isInteger(total) && (total as number) >= 0, 'baseline.smallHelperCopiesTotal must be a non-negative integer').toBe(true);
  return {
    measuredAt: record.measuredAt as string,
    note: record.note as string,
    oversizeFiles: readNumberMap(record, 'oversizeFiles'),
    moduleMutableState: readNumberMap(record, 'moduleMutableState'),
    smallHelperCopies: readNumberMap(record, 'smallHelperCopies'),
    smallHelperCopiesTotal: total as number,
  };
}

function sortedUnique(values: readonly string[]): string[] {
  return [...new Set(values)].sort();
}

/**
 * The ratchet comparison. A baseline entry may only fall; an entry OUTSIDE the baseline must obey
 * the dimension's absolute floor (`> 800` for lines, `> 0` for mutable state, `>= 2` declarations
 * for a helper name). Returns the violations (red) and the "baseline can be lowered" hints (green).
 */
export function compare(readings: Readings, baseline: Baseline): Comparison {
  const violations: string[] = [];
  const notes: string[] = [];

  const perFileDimension = (
    name: string,
    measured: Record<string, number>,
    pinned: Record<string, number>,
    isExternalViolation: (value: number) => boolean,
    rule: string,
  ): void => {
    const files = new Set([...Object.keys(pinned), ...Object.keys(measured)]);
    for (const file of [...files].sort()) {
      const now = measured[file] ?? 0;
      if (Object.prototype.hasOwnProperty.call(pinned, file)) {
        const was = pinned[file];
        if (now > was) {
          violations.push(`ratchet: ${name} ${file} ${was}→${now} — 基线内读数不得上调（此基线只允许下降）`);
        } else if (now < was) {
          notes.push(`ratchet: ${name} ${file} ${was}→${now}，可下调基线`);
        }
      } else if (isExternalViolation(now)) {
        violations.push(`ratchet: ${name} ${file} 基线外→${now} — ${rule}`);
      }
    }
  };

  perFileDimension('oversizeFiles', readings.oversizeFiles, baseline.oversizeFiles, (value) => value > OVERSIZE_LIMIT, `基线外的文件不得超过 ${OVERSIZE_LIMIT} 行`);
  perFileDimension('moduleMutableState', readings.moduleMutableState, baseline.moduleMutableState, (value) => value > 0, '基线外的文件模块级可变状态必须为 0');

  // Dimension three is keyed by helper NAME; the declaring files ride in the message so a red
  // always names a concrete path as well as the dimension.
  const helperFilesFor = (name: string): string => {
    const declaring = sortedUnique(readings.smallHelperFiles[name] ?? []);
    return declaring.length > 0 ? declaring.join(', ') : '<no file>';
  };
  const helperNames = new Set([...Object.keys(baseline.smallHelperCopies), ...Object.keys(readings.smallHelperCopies)]);
  for (const name of [...helperNames].sort()) {
    const now = readings.smallHelperCopies[name] ?? 0;
    if (Object.prototype.hasOwnProperty.call(baseline.smallHelperCopies, name)) {
      const was = baseline.smallHelperCopies[name];
      if (now > was) {
        violations.push(`ratchet: smallHelperCopies ${name} ${was}→${now} — 同名 helper 声明副本不得增加（files: ${helperFilesFor(name)}）`);
      } else if (now < was) {
        notes.push(`ratchet: smallHelperCopies ${name} ${was}→${now}，可下调基线`);
      }
    } else if (now >= HELPER_COPY_MIN) {
      violations.push(`ratchet: smallHelperCopies ${name} 基线外→${now} — 基线外不得新增同名 helper 副本（files: ${helperFilesFor(name)}）`);
    }
  }

  return { violations, notes };
}

