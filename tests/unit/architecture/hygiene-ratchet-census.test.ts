/**
 * Architecture hygiene ratchet census — three STRUCTURAL readings may only ever shrink.
 *
 * archguard already had per-layer guards (`layer-imports.test.ts`) and a delta checker, but no
 * standing census of the code smells the architecture review kept finding by hand: 1300-line
 * files, module-level mutable singletons, and copies of the same tiny helper. Without a committed
 * baseline nothing stopped a later commit from growing one of them back after a refactor shrank
 * it. This criterion serialises the three readings into one committed baseline and reds on the
 * FIRST commit that widens one of them, while printing a "可下调基线" hint when one falls.
 *
 * THE THREE DIMENSIONS (readings over every non-test `.ts` file under the repo-root `src/`):
 *
 *   1. `oversizeFiles`       file → line count, only for files over 800 lines.
 *   2. `moduleMutableState`  file → count. One reading is a column-0 line that starts `let `
 *                            (optionally `export let `), or a module-level
 *                            `const <id> … = new Map|Set|WeakMap`.
 *   3. `smallHelperCopies`   helper NAME → number of single-statement `function <name>(…) { … }`
 *                            declarations of that name across the scan set, only for names
 *                            declared at least twice. A "single-statement helper" is exactly
 *                            that shape — the copy-paste unit this census is about; a name that
 *                            is declared once is not a copy and is not a reading.
 *
 * THE RATCHET: a reading may FALL freely (the criterion prints
 * `ratchet: <dimension> <file|name> <baseline>→<measured>，可下调基线`), but it may never RISE.
 * A file/helper name OUTSIDE the committed baseline is not grandfathered in: an oversize file may
 * not exceed 800 lines, a mutable-state file must be 0, and a helper name outside the baseline may
 * not be declared twice or more. Lowering the committed baseline is encouraged but NOT required —
 * that is deliberate, so a parallel refactor task that shrinks a reading never reds this criterion.
 *
 * THE BASELINE IS GENERATED BY THE SAME READING. `measure()` below is the only scanner;
 * `npm run census:baseline` (or `HYGIENE_CENSUS_WRITE_BASELINE=1 npx vitest run
 * tests/unit/architecture/hygiene-ratchet-census.test.ts`) rewrites the committed JSON from it.
 * There is no second measurement implementation that can drift from the criterion.
 *
 * SCOPE: every non-test `.ts` under `<repo>/src/`. `node_modules/`, `dist/`, `tests/` and
 * `coverage/` DIRECTORIES are pruned; `*.test.ts`, `*.spec.ts`, `*.d.ts` and files whose basename
 * starts with `__` are dropped by name. The `__*` exclusion is deliberate: transient probes other
 * criteria drop into the tree must not change this census while it is running.
 */
