export type SourceFile = { path: string; text: string };

export type Readings = {
  oversizeFiles: Record<string, number>;
  moduleMutableState: Record<string, number>;
  /** Helper name → declaration count, only names declared at least HELPER_COPY_MIN times. */
  smallHelperCopies: Record<string, number>;
  /** Diagnostic index used to name files in a violation message. Not pinned in the baseline. */
  smallHelperFiles: Record<string, string[]>;
};

export type Baseline = {
  measuredAt: string;
  note: string;
  oversizeFiles: Record<string, number>;
  moduleMutableState: Record<string, number>;
  smallHelperCopies: Record<string, number>;
  smallHelperCopiesTotal: number;
};

export type Comparison = { violations: string[]; notes: string[] };

